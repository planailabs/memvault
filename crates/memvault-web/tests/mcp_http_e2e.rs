    let got = client
        .search_scoped(&entities_only, &word, 20)
        .await
        .unwrap();
    assert!(
        !got.is_empty() && got.iter().all(|h| h.node_type == "entity"),
        "{got:?}"
    );
    assert!(
        client
            .search_scoped(
                &QueryScope::all().with_bucket(Some(other.clone())),
                &word,
                20
            )
            .await
            .unwrap()
            .is_empty(),
        "another bucket's search finds nothing"
    );


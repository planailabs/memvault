#[tokio::test]
async fn docs_put_get_and_search() {
    let (client, bucket) = client_and_bucket().await;

    let mut fm = std::collections::BTreeMap::new();
    fm.insert("title".to_string(), serde_json::json!("Quarterly Report"));
    let doc = memvault_doc::Document {
        id: memvault_core::DocId([0u8; 32]), // ignored; server assigns the id
        frontmatter: fm,
        body: "the kangaroo metric improved this quarter".to_string(),
    };
    let cid = client
        .put_doc(doc.clone(), vec![], Visibility::Internal, Some(&bucket))
        .await
        .expect("put_doc");
    assert!(!cid.is_empty(), "put_doc returns a cid");

    // search used to discard the response; the hit carries the authoritative
    // DocId (distinct from the 36-byte block CID returned by put_doc).
    let hits = client.search("kangaroo", 10).await.expect("search");
    let doc_id = hits
        .first()
        .expect("search must find the indexed doc")
        .doc_id
        .clone();

    let got = client.get_doc(&doc_id).await.expect("get_doc");
    assert_eq!(
        got.expect("doc present").body,
        "the kangaroo metric improved this quarter"
    );

    // list_docs used to drop every row (server sent `doc:<hex>` labels, client
    // hand-parsed them as bare hex). It now decodes DocSummary directly.
    let docs = client
        .list_docs(None, 50, Some(&bucket))
        .await
        .expect("list_docs");
    assert!(
        docs.iter().any(|d| d.id == doc_id),
        "list_docs must return the doc it stored, got {} rows",
        docs.len()
    );
    // The summary's cid is the content address, round-trips as CID bytes.
    let summary = docs.iter().find(|d| d.id == doc_id).unwrap();
    assert!(!summary.cid.is_empty(), "DocSummary.cid must be populated");
}


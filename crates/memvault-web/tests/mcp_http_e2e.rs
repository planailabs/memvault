//! End-to-end tests for the memvault HTTP surface the openclaw MCP uses.
//!
//! These boot a **real** axum server over TCP, backed by an enrolled-agent
//! `LocalClient`, and drive it through `HttpApiClient` — the exact transport
//! the `mcp-memvault` plugin runs with (`MEMVAULT_URL=http://127.0.0.1:8401`).
//! Each MCP tool is a thin wrapper over a `MemvaultClient` call (or a
//! `memvault_api::vfs::*` helper that composes several), so exercising those
//! here covers the tool surface faithfully — and would have caught the stubbed
//! `add_link`/`edges_of`/`add_entity` paths that made `vfs_mkdir` return
//! entity:000…000 with no resolvable path.

use std::collections::{HashMap, HashSet};
use std::sync::Arc;

use ed25519_dalek::{Signer, SigningKey};
use tokio::sync::{OnceCell, RwLock};

use memvault_api::agent_identity::{enroll_local_agent, AgentIdentity};
use memvault_api::{EventBus, HttpApiClient, LocalClient, MemvaultClient};
use memvault_auth::node_attestation::{AttestationOrigin, NodeAttestation};
use memvault_auth::{jwt::NodeTrust, AgentRole};
use memvault_core::{AgentName, BucketId, ClusterId, NodeRef, PeerId, Visibility};
use memvault_doc::Entity;
use memvault_query::QuotaManager;
use memvault_store::MemvaultStore;
use memvault_web::{build_router, AppState};

const AGENT_ID: &str = "test-agent";

struct TestServer {
    base_url: String,
    identity: Arc<AgentIdentity>,
}

static SERVER: OnceCell<TestServer> = OnceCell::const_new();

/// Boot the enrolled-agent server once for the whole test binary.
async fn server() -> &'static TestServer {
    SERVER
        .get_or_init(|| async {
            // reqwest (used by HttpApiClient) is built with rustls-no-provider;
            // install a process-wide crypto provider before any client is built.
            let _ = rustls::crypto::ring::default_provider().install_default();

            // Deterministic admin + node keys; the agent key is generated by
            // `enroll_local_agent` and lives in `identity_dir`.
            let admin = SigningKey::from_bytes(&[0xA7u8; 32]);
            let node = SigningKey::from_bytes(&[0xB7u8; 32]);
            let cluster_id = ClusterId([0x11u8; 32]);

            let dir = std::env::temp_dir().join(format!("mv-mcp-e2e-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&dir);
            std::fs::create_dir_all(&dir).unwrap();
            // ACL helpers (enforce_*/filter_readable) lazily open the global
            // client from MEMVAULT_DB unless one is injected; point it at this
            // temp store so nothing touches a real ~/.local/share db.
            unsafe {
                std::env::set_var("MEMVAULT_DATA_DIR", &dir);
                std::env::set_var("MEMVAULT_DB", dir.join("blocks.redb"));
            }

            let store = Arc::new(MemvaultStore::open(dir.join("blocks.redb")).unwrap());
            let client = Arc::new(LocalClient::new(
                store,
                Arc::new(RwLock::new(QuotaManager::new(Default::default()))),
                Arc::new(EventBus::new(64)),
                node.verifying_key().to_bytes().to_vec(),
                cluster_id.0.to_vec(),
            ));

            // Minimal genesis so the agent can be enrolled and ACL resolves.
            let genesis = memvault_auth::sign_admin_genesis(&admin, cluster_id.clone(), 1)
                .expect("sign_admin_genesis");
            client.set_admin_signing_key(admin.clone());
            client.set_pinned_admin_genesis(genesis);
            client.set_node_signing_key(node.clone());

            let identity = enroll_local_agent(
                &client,
                AGENT_ID,
                &dir.join("agent"),
                AgentRole::AgentHost,
                u64::MAX,
            )
            .expect("enroll_local_agent");
            let agent_pubkey = identity.verifying_key.to_bytes();

            // The ACL helpers consult the process-global client.
            memvault_web::ui::state::set_client(Arc::clone(&client));

            // Auth fixtures: admin-signed node attestation (node_trust) and an
            // agent-attestation lookup matching the enrolled agent.
            let mut node_att = NodeAttestation {
                cluster_id: cluster_id.clone(),
                member: PeerId(node.verifying_key().as_bytes().to_vec()),
                not_after_ns: u64::MAX,
                issued_via: AttestationOrigin::Direct,
                signature: [0u8; 64],
            };
            node_att.signature = admin.sign(&node_att.signing_bytes().unwrap()).to_bytes();
            let mut trust = HashMap::new();
            trust.insert(node.verifying_key().to_bytes(), NodeTrust::Attested(node_att));

            let agent_att = memvault_auth::sign_agent_attestation(
                &node,
                AgentName(AGENT_ID.to_string()),
                agent_pubkey,
                AgentRole::AgentHost,
                u64::MAX,
            )
            .expect("sign_agent_attestation");
            let lookup_att = agent_att.clone();

            let state = Arc::new(AppState {
                client: Arc::clone(&client) as Arc<dyn MemvaultClient>,
                event_bus: Arc::new(EventBus::new(16)),
                admin_pubkey: Some(admin.verifying_key()),
                node_trust: Arc::new(std::sync::RwLock::new(trust)),
                revoked_agents: Arc::new(std::sync::RwLock::new(HashSet::new())),
                revoked_nodes: Arc::new(std::sync::RwLock::new(HashSet::new())),
                metrics: Arc::new(memvault_api::metrics::Metrics::new()),
                agent_attestation_lookup: Some(Arc::new(move |pk: &[u8; 32]| {
                    (*pk == lookup_att.agent_pubkey).then(|| lookup_att.clone())
                })),
                allowed_origins: vec![],
            });

            let router = build_router(state);

            // Run the server on its OWN thread + runtime. `#[tokio::test]`
            // gives each test a fresh runtime that is torn down when the test
            // ends; a server spawned on the first test's runtime would die and
            // every later test would see "error sending request". A dedicated
            // thread keeps it alive for the whole test binary.
            let (tx, rx) = std::sync::mpsc::channel();
            std::thread::spawn(move || {
                let rt = tokio::runtime::Builder::new_current_thread()
                    .enable_all()
                    .build()
                    .unwrap();
                rt.block_on(async move {
                    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
                    tx.send(listener.local_addr().unwrap()).unwrap();
                    let _ = axum::serve(listener, router).await;
                });
            });
            let addr = rx.recv().unwrap();

            TestServer {
                base_url: format!("http://{addr}"),
                identity: Arc::new(identity),
            }
        })
        .await
}

/// An authenticated HTTP client + the enrolled agent's own bucket.
async fn client_and_bucket() -> (HttpApiClient, BucketId) {
    let s = server().await;
    let client = HttpApiClient::new(&s.base_url, Some(Arc::clone(&s.identity))).unwrap();
    // The server derives the bucket from the JWT pubkey; the bytes here are
    // ignored over HTTP. Pass the real identity pubkey anyway.
    let bucket = client
        .ensure_agent_bucket(&s.identity.verifying_key.to_bytes(), AGENT_ID)
        .await
        .expect("ensure_agent_bucket");
    (client, bucket)
}

/// A dedicated bucket so VFS tests don't race on a shared root.
async fn fresh_bucket(client: &HttpApiClient, name: &str) -> BucketId {
    client
        .bucket_create(
            name,
            None,
            Visibility::Internal,
            memvault_core::classification::Classification::Internal,
            memvault_doc::BucketRole::Standard,
        )
        .await
        .expect("bucket_create")
}

const ZERO: [u8; 32] = [0u8; 32];

#[tokio::test]
async fn vfs_mkdir_resolve_ls_tree_round_trip() {
    let (client, _agent_bucket) = client_and_bucket().await;
    let bucket = fresh_bucket(&client, "vfs-mkdir-test").await;

    // mkdir -p /reports/2026 — the regression: this used to return
    // entity:000…000 and leave nothing resolvable.
    let id = client
        .vfs_mkdir(&bucket, "/reports/2026")
        .await
        .expect("mkdir");
    assert_ne!(id.0, ZERO, "mkdir must return a real (non-zero) entity id");

    // The leaf resolves.
    let resolved = client
        .vfs_resolve(&bucket, "/reports/2026")
        .await
        .expect("resolve_path");
    assert!(resolved.is_some(), "freshly created dir must resolve");

    // ls / shows reports.
    let entries = client
        .vfs_ls(&bucket, "/", false)
        .await
        .expect("ls");
    assert!(
        entries.iter().any(|e| e.name == "reports"),
        "ls / must list the new 'reports' dir, got {:?}",
        entries.iter().map(|e| &e.name).collect::<Vec<_>>()
    );

    // tree contains the nested path.
    let tree = client
        .vfs_tree(&bucket, "/", 10)
        .await
        .expect("tree");
    assert!(tree.contains("2026"), "tree must include the nested dir: {tree}");
}

#[tokio::test]
async fn graph_entity_and_edges_round_trip() {
    let (client, bucket) = client_and_bucket().await;

    let mut props = std::collections::BTreeMap::new();
    props.insert("name".to_string(), serde_json::json!("alice"));
    let parent = client
        .add_entity(
            Entity {
                id: memvault_core::EntityId::random(),
                kind: "person".to_string(),
                props: props.clone(),
                edges_out: vec![],
            },
            Visibility::Internal,
            Some(&bucket),
        )
        .await
        .expect("add_entity parent");
    assert_ne!(parent.0, ZERO, "add_entity must not return a zero id");

    // get_entity round-trips.
    let got = client.get_entity(&parent).await.expect("get_entity");
    assert_eq!(got.expect("entity present").kind, "person");

    let child = client
        .add_entity(
            Entity {
                id: memvault_core::EntityId::random(),
                kind: "person".to_string(),
                props,
                edges_out: vec![],
            },
            Visibility::Internal,
            Some(&bucket),
        )
        .await
        .expect("add_entity child");

    let parent_ref = NodeRef::Entity(parent);
    let child_ref = NodeRef::Entity(child);

    // add_link used to be a no-op returning a random id; now it persists.
    let edge = memvault_doc::Edge {
        id: memvault_core::EdgeId::random(),
        relation: "knows".to_string(),
        target: child_ref.clone(),
        weight: None,
        props: Default::default(),
        provenance: None,
    };
    client
        .add_link(&parent_ref, edge, Visibility::Internal)
        .await
        .expect("add_link");

    // edges_of used to discard the response; now it returns the edge.
    let edges = client.edges_of(&parent_ref).await.expect("edges_of");
    assert!(
        edges
            .iter()
            .any(|(src, e)| *src == parent_ref && e.relation == "knows" && e.target == child_ref),
        "edges_of must return the persisted 'knows' edge"
    );
}


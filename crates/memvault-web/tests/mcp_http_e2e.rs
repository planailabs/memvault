#[tokio::test]
async fn vfs_link_unlink_round_trip() {
    let (client, _agent_bucket) = client_and_bucket().await;
    let bucket = fresh_bucket(&client, "vfs-link-test").await;

    // Create an entity (its 32-byte id is known exactly), link it at a VFS
    // path, confirm it resolves, then unlink.
    let entity = client
        .add_entity(
            Entity {
                id: memvault_core::EntityId::random(),
                kind: "note".to_string(),
                props: Default::default(),
                edges_out: vec![],
            },
            Visibility::Internal,
            Some(&bucket),
        )
        .await
        .expect("add_entity");
    let node_id = format!("entity:{}", hex::encode(entity.0));

    let target = memvault_core::NodeRef::from_tag_label(&node_id).expect("node ref");
    client
        .vfs_link(&bucket, "/notes/linked.md", &target)
        .await
        .expect("vfs_link");

    let resolved = client
        .vfs_resolve(&bucket, "/notes/linked.md")
        .await
        .expect("resolve_path");
    assert!(resolved.is_some(), "linked node must resolve at its path");

    client
        .vfs_unlink(&bucket, "/notes/linked.md")
        .await
        .expect("unlink_path");
    let after = client
        .vfs_resolve(&bucket, "/notes/linked.md")
        .await
        .expect("resolve_path after unlink");
    assert!(after.is_none(), "node must be gone after unlink");
}

